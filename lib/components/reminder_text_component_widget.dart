/// a formatted view of an existing reminder
class ReminderTextComponentWidget extends StatefulWidget {
  const ReminderTextComponentWidget({
    super.key,
    required this.reminderRef,
  });

  final DocumentReference? reminderRef;

  @override
  State<ReminderTextComponentWidget> createState() =>
      _ReminderTextComponentWidgetState();
}

class _ReminderTextComponentWidgetState
    extends State<ReminderTextComponentWidget> {
  late ReminderTextComponentModel _model;

  @override
  void setState(VoidCallback callback) {
    super.setState(callback);
    _model.onUpdate();
  }

  @override
  void initState() {
    super.initState();
    _model = createModel(context, () => ReminderTextComponentModel());

    WidgetsBinding.instance.addPostFrameCallback((_) => safeSetState(() {}));
  }

  @override
  void dispose() {
    _model.maybeDispose();

    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return StreamBuilder<RemindersRecord>(
      stream: RemindersRecord.getDocument(widget!.reminderRef!),
      builder: (context, snapshot) {
        // Customize what your widget looks like when it's loading.
        if (!snapshot.hasData) {
          return Center(
            child: SizedBox(
              width: 40.0,
              height: 40.0,
              child: CircularProgressIndicator(
                valueColor: AlwaysStoppedAnimation<Color>(
                  FlutterFlowTheme.of(context).primary,
                ),
              ),
            ),
          );
        }

        final textRemindersRecord = snapshot.data!;

        return Text(
          '${functions.listToString(textRemindersRecord.days.toList())} at ${dateTimeFormat("jm", textRemindersRecord.time)}',
          style: FlutterFlowTheme.of(context).bodyMedium.override(
                font: GoogleFonts.poppins(
                  fontWeight:
                      FlutterFlowTheme.of(context).bodyMedium.fontWeight,
                  fontStyle: FlutterFlowTheme.of(context).bodyMedium.fontStyle,
                ),
                fontSize: 12.0,
                letterSpacing: 0.0,
                fontWeight: FlutterFlowTheme.of(context).bodyMedium.fontWeight,
                fontStyle: FlutterFlowTheme.of(context).bodyMedium.fontStyle,
              ),
        );
      },
    );
  }
}
